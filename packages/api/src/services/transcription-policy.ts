/**
 * 152-ФЗ: единственная точка, где принимается решение «можно ли уйти в облачный
 * OpenAI whisper-1». Сырая запись голоса — самые чувствительные персданные, а
 * отправка в OpenAI — трансграничная передача в США.
 *
 * Раньше эта функция жила в `routes/meetings.ts` и была экспортирована оттуда
 * только ради теста — но веб-загрузка встречи не единственный путь, которым
 * аудио может уехать в OpenAI. Проверено (см. отчёт задачи) ещё три места,
 * которые звали `openai.audio.transcriptions.create` МИМО этой проверки:
 * `services/whisper-queue.ts` (очередь расшифровки Telegram, включая прямой,
 * не-фолбэчный путь для плана pro_max), `parsers/audio.parser.ts` (загрузка
 * аудио через /v1/ingest — там вообще нет локальной альтернативы), и команда
 * `/transcribe <ссылка>` в `services/telegram.service.ts`. Вынесено сюда,
 * чтобы каждый из этих путей звал ОДНУ и ту же проверку, а не копировал
 * условие — иначе флаг гарантированно рассинхронизируется с реальностью
 * при следующей правке одного из путей.
 */
export function assertCloudFallbackAllowed(cloudFallbackAllowed: boolean, reason: string): void {
  if (cloudFallbackAllowed) return;
  throw new Error(
    `${reason}, а облачный фолбэк отключён политикой обработки персональных данных (152-ФЗ). Попробуйте ещё раз позже или обратитесь к администратору.`
  );
}
