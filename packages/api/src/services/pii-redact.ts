/**
 * Обезличивание персональных данных перед отправкой текста в LLM (152-ФЗ).
 *
 * Формула: наружу — только обезличенный текст, таблица соответствия token → значение
 * остаётся у нас (никогда не логируется, не сохраняется в БД, не индексируется),
 * подстановка исходных значений обратно делается нашим кодом после ответа модели.
 *
 * Покрытые классы данных: телефоны (RU-формат с префиксом, RU-мобильный без
 * префикса, международный `+код`), email, ФИО (двух- и трёхсловные, латиница,
 * сокращённые формы «Фамилия И.О.» / «И. Фамилия»). Осознанно НЕ покрыты: паспорт,
 * ИНН, СНИЛС, дата рождения, почтовый адрес, telegram-хендлы — каждый из них либо
 * легко спутать с обычными числами/словами транскрипта (даты рождения неотличимы
 * от дат встречи без контекста), либо требует отдельной проработки границ и
 * тестов. Замалчивать это не хотим: если понадобится покрыть — это отдельная
 * доработка данного модуля, а не факт, который уже тут "подразумевается".
 */

export type PiiMap = Record<string, string>;

// ── Телефоны ─────────────────────────────────────────────────────────────
// Границы по цифрам (?<!\d) / (?!\d) обязательны: без них "Заказ 89161234567890"
// матчился частично (первые 11 цифр), а хвост "890" утекал в модель как обрывок
// заведомо испорченного числа — то есть визуально выглядело как обезличивание,
// но было им лишь наполовину.
//
// Найдено ревью (реальная утечка): помимо "+7" и "8" номер телефона на практике
// часто пишут с голым "7" впереди — "79161234567" — именно так его отдают
// CRM-выгрузки и веб-формы. Такой вид не попадал ни под этот паттерн (нужен был
// литеральный "+7" или "8"), ни под PHONE_RU_BARE (границу (?<!\d) перед "9"
// блокировала предшествующая цифра "7") — номер целиком уходил в модель в
// открытом виде. Добавление "7" в альтернативу префикса симметрично уже
// принятому компромиссу для "8" (тоже частая первая цифра много чего, но здесь
// осознанно трактуется как телефон) и не создаёт новых частичных совпадений
// внутри более длинных цифровых последовательностей: любая "7"/"8" ВНУТРИ
// длинного числа стоит после цифры, поэтому (?<!\d) её как начало совпадения
// не пропускает, а если совпадение всё же начинается на границе, дальше
// требуется ровно 10 цифр без переходов длины — (?!\d) в конце отклоняет
// частичный захват, как и раньше для "Заказ 89161234567890" и банковского счёта.
const PHONE_RU = /(?<!\d)(?:\+7|8|7)[\s(-]*\d{3}[\s)-]*\d{3}[\s-]*\d{2}[\s-]*\d{2}(?!\d)/g;
/** Мобильный без кода страны — так его чаще всего диктуют вслух: "916 123-45-67". */
const PHONE_RU_BARE = /(?<!\d)9\d{2}[\s-]?\d{3}[\s-]?\d{2}[\s-]?\d{2}(?!\d)/g;
/** Любой другой код страны: "+375 29 1234567" и т.п. */
const PHONE_INTL = /(?<!\d)\+\d{1,3}[\s(-]*\d{2,4}[\s)-]*\d{3,4}[\s-]*\d{0,4}[\s-]*\d{0,4}(?!\d)/g;

const EMAIL = /[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}/g;

// ── ФИО ──────────────────────────────────────────────────────────────────
// В JS \b определяется через ASCII \w и не работает на кириллице — граница между
// пробелом и русской буквой для движка не граница (обе стороны "не-словесные"),
// поэтому \b перед/после кириллических слов просто никогда не срабатывает.
// Заменяем его на явные лукэраунды по кириллическому алфавиту (аналогично для
// латиницы — свой лукэраунд по [A-Za-z]).
const CYR = 'А-Яа-яЁё';

/**
 * Два ИЛИ три слова с заглавной подряд — кандидат в ФИО. Жадный (по умолчанию для
 * `?`), поэтому съедает тройную форму «Имя Отчество Фамилия» целиком одним токеном:
 * не жадный вариант останавливался на первых двух словах и оставлял фамилию
 * (самый идентифицирующий компонент) в открытом виде — например
 * «Иван Петрович Сидоров» превращалось в «[УЧАСТНИК_1] Сидоров».
 *
 * Ревью нашло парную проблему от той же жадности: третье слово захватывалось
 * ДАЖЕ когда на самом деле это начало ИМЕНИ СЛЕДУЮЩЕГО ЧЕЛОВЕКА — «Иван Петров
 * Мария Соколова» превращалось в «[УЧАСТНИК_1] Соколова», а в карте оказывалось
 * «Иван Петров Мария» — фамилия второго участника опять утекала. Лукахед
 * `(?![ \t][А-ЯЁ][а-яё]{2,})` после третьего слова запрещает его захват, если
 * СРАЗУ ЗА НИМ идёт ещё одно слово, САМО похожее на имя (заглавная + минимум
 * два строчных символа) через пробел — то есть если весь ряд похож не на «Имя
 * Отчество Фамилия», а на два двухсловных имени подряд. Тройная форма (за
 * которой следует пунктуация, конец строки или обычное слово) продолжает
 * ловиться целиком, как и раньше — второй пример из ревью проверен тестом ниже.
 *
 * Третье ревью нашло регресс ровно в этом лукэхеде: первая версия проверяла
 * ОДНУ заглавную букву после третьего слова — `(?![ \t][А-ЯЁ])` — а не то,
 * похож ли следующий токен САМ на слово-имя. Из-за этого лукэхед срабатывал и
 * на акронимах («МТС»), организационно-правовых формах («ООО») и коротких
 * словах («Ян») — третья группа выбрасывалась целиком, а фамилия, которую она
 * держит, уходила в модель в открытом виде: «Иван Петрович Сидоров МТС
 * подтвердил» → «[УЧАСТНИК_1] Сидоров МТС подтвердил». Второй проход это не
 * спасал: фамилия никогда не регистрировалась как компонент имени, потому что
 * вся тройная группа была необязательной и просто не сработала. Требование
 * `{2,}` строчных букв после заглавной в лукэхеде — это и есть проверка «следующий
 * токен похож на имя», а не на любое слово с большой буквы: акронимы (все
 * заглавные) и однобуквенные инициалы под неё не подпадают и больше не
 * подавляют захват третьего слова.
 *
 * Известный компромисс: исключения по границе предложения нет вообще — см. ниже.
 * Различить «Иван Петров» и «Сроки Горят», когда оба стоят в позиции 0 всей строки,
 * средствами одной регулярки без словаря имён нельзя. В транскриптах встреч реплики
 * почти всегда оформлены как «Имя Фамилия: текст» с новой строки — то есть ровно там,
 * где раньше стоявшее исключение срабатывало, и реальные имена спикеров пролетали
 * мимо обезличивания (проверено на синтетическом транскрипте, см. отчёт задачи).
 * Пропуск имени — утечка; лишняя замена в «Сроки Горят потому что…» — испорченный
 * кусок текста, не утечка. Поэтому исключения нет: точность ниже, зато ни одно ФИО
 * не проходит мимо редактирования независимо от позиции в тексте.
 */
const FULLNAME = new RegExp(
  `(?<![${CYR}])([А-ЯЁ][а-яё]{2,})[ \\t]+([А-ЯЁ][а-яё]{2,})(?:[ \\t]+([А-ЯЁ][а-яё]{2,})(?![ \\t][А-ЯЁ][а-яё]{2,}))?(?![${CYR}])`,
  'g'
);
/** Латинские имена: «John Smith», «Anna Lee» — участники из международных встреч. */
const LATIN_NAME = /(?<![A-Za-z])([A-Z][a-z]{2,})[ \t]+([A-Z][a-z]{2,})(?![A-Za-z])/g;
/** «Ольга К.» / «Петров И.И.» — имя или фамилия с одним-двумя инициалами после. */
const INITIALS_AFTER = new RegExp(`(?<![${CYR}])([А-ЯЁ][а-яё]{2,})[ \\t]+((?:[А-ЯЁ]\\.){1,2})(?![${CYR}])`, 'g');
/** «А. Смирнов» / «И.О. Петров» — один-два инициала перед фамилией. */
const INITIALS_BEFORE = new RegExp(`(?<![${CYR}])((?:[А-ЯЁ]\\.){1,2})[ \\t]?([А-ЯЁ][а-яё]{2,})(?![${CYR}])`, 'g');
/** Одиночное слово-кандидат — сверяется со словарём компонентов, найденных выше. */
const SINGLE_CYR_WORD = new RegExp(`(?<![${CYR}])([А-ЯЁ][а-яё]{2,})(?![${CYR}])`, 'g');
const SINGLE_LATIN_WORD = /(?<![A-Za-z])([A-Z][a-z]{2,})(?![A-Za-z])/g;
/** Инициал вида "И." или "И.О." — не самостоятельное слово, в словарь компонентов не идёт. */
const IS_INITIALS_GROUP = /^[А-ЯЁ]\.([А-ЯЁ]\.)?$/;

/**
 * Заменяет персональные данные на стабильные токены.
 * В модель уходит только `text`; `map` остаётся на нашей стороне и в логи/промпты
 * не попадает никогда — вызывающий код обязан держать её только в переменной.
 *
 * Многословные и сокращённые формы ФИО обрабатываются первым проходом. Второй
 * проход ищет одиночные слова, которые уже встретились как компонент найденного
 * имени (например «Иван» после «Иван Петров:» в реплике дальше по тексту).
 *
 * Важно про второй проход (найдено ревью): раньше такое одиночное слово получало
 * ТОТ ЖЕ токен, что и полное имя, и restorePii подставляло обратно ВСЮ фразу
 * целиком. Для настоящих имён это выглядело удобно, но у метода без словаря имён
 * компонентом мог оказаться и обычное слово из ложного срабатывания ФИО
 * («Сроки» из «Сроки Горят», «Москва» из «Москва Сити», «Директоров» из «Совет
 * Директоров») — и тогда следующее обычное упоминание того же слова в СОВСЕМ
 * другом предложении получало чужой токен, а restorePii молча дописывало в текст
 * вторую половину когда-то распознанной "фамилии". Испорченный текст уходил в
 * summary_raw, vault и поисковый индекс необратимо. Починено переходом на
 * отдельный токен для каждого одиночного слова, привязанный ТОЛЬКО к этому слову
 * (map хранит само слово, а не всю фразу) — резюме теряет красивое «слипание»
 * «Иван» → «Иван Петров», но получает главное: restorePii больше не может
 * подставить обратно то, чего не было ровно в этом месте текста. Круговой прогон
 * redactPii → restorePii теперь равен исходному тексту всегда, а не «почти
 * всегда, кроме повторов слов-компонентов».
 */
export function redactPii(text: string): { text: string; map: PiiMap } {
  const map: PiiMap = {};
  const seen = new Map<string, string>();
  const counters: Record<string, number> = { ТЕЛЕФОН: 0, EMAIL: 0, УЧАСТНИК: 0 };
  const nameComponents = new Set<string>();

  const issueToken = (value: string, kind: string): string => {
    const existing = seen.get(value);
    if (existing) return existing;
    counters[kind] = (counters[kind] ?? 0) + 1;
    const token = `[${kind}_${counters[kind]}]`;
    seen.set(value, token);
    map[token] = value;
    return token;
  };

  const registerComponents = (groups: Array<string | undefined>): void => {
    for (const g of groups) {
      if (!g || IS_INITIALS_GROUP.test(g)) continue;
      nameComponents.add(g);
    }
  };

  const replace = (input: string, re: RegExp, kind: string, onGroups?: (groups: Array<string | undefined>) => void): string =>
    input.replace(re, (match: string, ...rest: unknown[]) => {
      const groups = rest.filter((g): g is string => typeof g === 'string');
      const token = issueToken(match, kind);
      onGroups?.(groups);
      return token;
    });

  let out = text;
  out = replace(out, EMAIL, 'EMAIL');
  out = replace(out, PHONE_RU, 'ТЕЛЕФОН');
  out = replace(out, PHONE_RU_BARE, 'ТЕЛЕФОН');
  out = replace(out, PHONE_INTL, 'ТЕЛЕФОН');
  out = replace(out, FULLNAME, 'УЧАСТНИК', registerComponents);
  out = replace(out, LATIN_NAME, 'УЧАСТНИК', registerComponents);
  out = replace(out, INITIALS_AFTER, 'УЧАСТНИК', registerComponents);
  out = replace(out, INITIALS_BEFORE, 'УЧАСТНИК', registerComponents);

  // Второй проход: одиночные слова, уже встреченные как компонент найденного имени.
  // Каждое СВОЁ отдельное слово — свой токен, привязанный только к этому слову
  // (см. комментарий у redactPii про порчу текста, найденную ревью).
  const replaceSingle = (input: string, re: RegExp): string =>
    input.replace(re, (word: string) => (nameComponents.has(word) ? issueToken(word, 'УЧАСТНИК') : word));
  out = replaceSingle(out, SINGLE_CYR_WORD);
  out = replaceSingle(out, SINGLE_LATIN_WORD);

  return { text: out, map };
}

const TOKEN_KINDS = ['ТЕЛЕФОН', 'EMAIL', 'УЧАСТНИК'] as const;
/**
 * Терпима к регистру и разделителю: модель, пишущая связное резюме, может отдать
 * «Участник 1», «[Участник_1]» или «[УЧАСТНИК 1]» вместо точного «[УЧАСТНИК_1]».
 * Без этой терпимости restorePii менял бы только точные совпадения, и искажённый
 * токен молча оставался бы в тексте — а оттуда в БД и в поисковый индекс.
 */
const TOLERANT_TOKEN_RE = new RegExp(`\\[\\s*(${TOKEN_KINDS.join('|')})[\\s_]*(\\d+)\\s*\\]`, 'gi');

/**
 * Подстановка реальных значений обратно — уже у нас, без участия модели.
 *
 * Известный остаточный риск (принят осознанно, не устранён): если бы в САМОМ
 * транскрипте до обезличивания буквально встретилась строка вида «[EMAIL_1]»
 * (что практически невозможно для расшифровки речи), restorePii подставила бы
 * туда чужой адрес из карты. Это неизбежное следствие любой плейсхолдер-схемы;
 * при формате токена, не встречающемся в естественной речи, риск пренебрежимо мал.
 */
export function restorePii(text: string, map: PiiMap): string {
  return text.replace(TOLERANT_TOKEN_RE, (whole, kindRaw: string, num: string) => {
    const kind = TOKEN_KINDS.find((k) => k.toLowerCase() === kindRaw.toLowerCase());
    if (!kind) return whole;
    const canonical = `[${kind}_${num}]`;
    return Object.prototype.hasOwnProperty.call(map, canonical) ? map[canonical]! : whole;
  });
}

/**
 * Тип нераспознанного остатка: КАКОЙ класс данных и ГДЕ он встретился в тексте —
 * никогда сам текст совпадения и уж тем более не значение из таблицы соответствия.
 * См. подробности в комментарии у `findResidualPiiTokens` ниже.
 */
export interface ResidualPiiToken {
  /** Класс данных, к которому относится нераспознанный токен. */
  kind: (typeof TOKEN_KINDS)[number];
  /** Смещение начала совпадения в переданном тексте (индекс символа) — для навигации в логах. */
  index: number;
}

/**
 * Сканирует текст ПОСЛЕ restorePii на остаточные токены — те, что модель исказила
 * настолько, что даже терпимый restorePii не смог их опознать (несуществующий
 * номер участника, мусор внутри скобок и т.п.), А ТАКЖЕ на токены, пересказанные
 * словами вместо плейсхолдера («Участник 1» вместо «[УЧАСТНИК_1]») — несмотря на
 * явную инструкцию в PII_TOKEN_NOTE модель иногда всё равно так делает.
 *
 * ЧЕТВЁРТОЕ ревью нашло структурный дефект во всех трёх предыдущих версиях этой
 * функции: она возвращала САМ СОВПАВШИЙ ТЕКСТ, а вызывающий код (restorePiiAndWarn,
 * restorePiiDeepAndWarn) логировал этот текст как есть. Скан работает ПОСЛЕ
 * restorePii — то есть на тексте, где токены уже подставлены обратно на настоящие
 * значения. Стоило без-скобочной эвристике (а по конструкции она ловит «слово +
 * разделитель + цифры», какой бы конкретной формулировкой её ни сузили) совпасть на
 * обычной фразе «Телефон 89161234567», где «Телефон» — обычное слово в начале
 * предложения, а «89161234567» — РЕАЛЬНЫЙ восстановленный номер, — и в
 * `console.warn`, а оттуда в PM2-лог, уходил настоящий телефон клиента. Три
 * предыдущих ревью каждый раз сужали регулярку под конкретный репродукс и открывали
 * дыру с другой стороны (сузили под слитный номер — потеряли продиктованный по
 * группам; сузили под продиктованный — снова приняли слитный, самый частый в жизни
 * формат). Дальнейшее сужение бесполезно: пока функция возвращает совпавший текст,
 * всегда найдётся вход, где этот текст — настоящие персональные данные.
 *
 * Починка структурная, не регулярочная: функция возвращает ТОЛЬКО класс токена
 * (`kind`) и позицию совпадения (`index`), см. `ResidualPiiToken`. Ни сам текст
 * совпадения, ни тем более значение из таблицы соответствия никогда не попадают ни
 * в возвращаемое значение, ни в лог — `console.warn` формирует строку вида
 * «[pii] meeting #42: не восстановлено 2 токена (УЧАСТНИК@31, ТЕЛЕФОН@88)»: этого
 * достаточно, чтобы найти место в тексте и разобраться, но утечь структурно нечем,
 * какой бы текст ни совпал под капотом регулярки.
 *
 * Ровно это позволяет БЕЗ риска утечки вернуть эвристике чувствительность,
 * потерянную тремя предыдущими раундами сужения (избыточное совпадение — теперь
 * просто шум в логе, а не утечка):
 * - строчная форма с ПРОБЕЛОМ («телефон 3 не отвечает», «участник 1 подтвердил
 *   встречу», «email 2 отправлен») снова ловится — раньше для этого требовалось
 *   подчёркивание;
 * - число больше не запрещено продолжаться другим числом через пробел или перенос
 *   строки — «1. Участник 1\n2. Участник 2 согласился» и «Участник 1 2 вопроса»
 *   раньше находили только второе вхождение: цифро-защитный лукэхед принимал номер
 *   следующего пункта списка или второе число подряд за начало продиктованного
 *   телефона и подавлял совпадение.
 *
 * Единственное оставшееся ограничение — длина числа после ТЕЛЕФОН (1–3 цифры без
 * продолжения ни слитно, ни через пробел): это уже не защита от утечки (утечки
 * структурно больше нет), а защита ТОЧНОСТИ лога — без неё «телефон 89161234567»
 * (реальный слитный номер) и «Телефон 8 916 123 45 67» (реальный номер,
 * продиктованный по группам) считались бы искажёнными токенами почти при каждом
 * упоминании телефона в резюме, а предупреждение превратилось бы в шум и его
 * стали бы игнорировать. У EMAIL и УЧАСТНИК такой коллизии с настоящими
 * восстановленными значениями нет (имена не состоят из одних цифр, email не
 * начинается с цифры сразу после слова «email»/«участник» в естественной речи),
 * поэтому там ограничения длины числа нет.
 */
export function findResidualPiiTokens(text: string): ResidualPiiToken[] {
  const WORD = `A-Za-z${CYR}`;
  const toTitle = (s: string): string => s[0]! + s.slice(1).toLowerCase();
  const results: ResidualPiiToken[] = [];
  const seen = new Set<string>();

  const addMatches = (re: RegExp, kind: (typeof TOKEN_KINDS)[number]): void => {
    for (const m of text.matchAll(re)) {
      const key = `${kind}@${m.index}`;
      if (seen.has(key)) continue;
      seen.add(key);
      results.push({ kind, index: m.index! });
    }
  };

  for (const kind of TOKEN_KINDS) {
    const title = toTitle(kind);
    const lower = kind.toLowerCase();

    // Скобочная форма: «[УЧАСТНИК_1]», «[Участник_1]», «[ТЕЛЕФОН 3]» и т.п. —
    // однозначна по конструкции (заключена в скобки), длину числа не ограничиваем.
    addMatches(new RegExp(`\\[\\s*${kind}[\\s_]*\\d*\\s*\\]`, 'gi'), kind);

    // Без-скобочная форма — любой регистр слова (ТЕЛЕФОН / Телефон / телефон),
    // разделитель пробел или подчёркивание. Для ТЕЛЕФОН число ограничено 1-3
    // цифрами без продолжения — см. комментарий выше про коллизию с настоящими
    // восстановленными номерами.
    const digits = kind === 'ТЕЛЕФОН' ? '\\d{1,3}(?!\\d)(?!\\s?\\d)' : '\\d+';
    addMatches(new RegExp(`(?<![${WORD}\\[])(?:${kind}|${title}|${lower})[\\s_]+${digits}`, 'g'), kind);
  }

  results.sort((a, b) => a.index - b.index);
  return results;
}

/** Русское склонение слова «токен» под число — для строки предупреждения ниже. */
function pluralizeTokenWord(n: number): string {
  const mod10 = n % 10;
  const mod100 = n % 100;
  if (mod10 === 1 && mod100 !== 11) return 'токен';
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 10 || mod100 >= 20)) return 'токена';
  return 'токенов';
}

/**
 * Собирает ОДНУ строку предупреждения из структурного результата
 * `findResidualPiiTokens` — общий формат для restorePiiAndWarn и
 * restorePiiDeepAndWarn. В строке только класс и позиция каждого остатка
 * (например «УЧАСТНИК@31»), никогда сам совпавший текст и тем более значение
 * из таблицы соответствия — см. комментарий у findResidualPiiTokens.
 */
function formatResidualWarning(context: string, residual: ResidualPiiToken[]): string {
  const list = residual.map((r) => `${r.kind}@${r.index}`).join(', ');
  return `[pii] ${context}: не восстановлено ${residual.length} ${pluralizeTokenWord(residual.length)} (${list})`;
}

/**
 * Обёртка над restorePii, которую обязан использовать любой вызывающий код на
 * любом пути отправки текста в модель: восстанавливает ПД и предупреждает через
 * console.warn, если что-то не восстановилось (модель исказила токен сильнее, чем
 * понимает терпимый restorePii). В лог уходит ОДНА строка вида «[pii] context: не
 * восстановлено N токена (КЛАСС@позиция, ...)» — класс и позиция остатка, НИКОГДА
 * сам совпавший текст и тем более значение из таблицы соответствия (см.
 * findResidualPiiTokens и formatResidualWarning выше).
 */
export function restorePiiAndWarn(text: string, map: PiiMap, context: string): string {
  const restored = restorePii(text, map);
  const residual = findResidualPiiTokens(restored);
  if (residual.length) {
    console.warn(formatResidualWarning(context, residual));
  }
  return restored;
}

/**
 * Разделитель для склейки нескольких полей (транскрипт + название + список
 * участников и т.п.) в ОДИН вызов redactPii — так одно и то же имя, встретившееся
 * в разных полях, получает один и тот же токен. Отдельные вызовы redactPii на
 * каждое поле дали бы РАЗНЫЕ токены одному и тому же человеку.
 */
export const PII_JOIN_BOUNDARY = '\n --pii-boundary-- \n';

/** Склеивает несколько полей `PII_JOIN_BOUNDARY` перед вызовом redactPii. */
export function joinForRedaction(parts: string[]): string {
  return parts.join(PII_JOIN_BOUNDARY);
}

/**
 * Разбирает склеенный через joinForRedaction/redactPii текст обратно на count
 * исходных полей. Использует indexOf, а не String.split(boundary): если
 * разделитель гипотетически встретился бы в самом содержимом поля, split()
 * резал бы его неверно — здесь только первые (count-1) вхождений считаются
 * границами, весь остаток целиком уходит в последнее поле.
 */
export function splitRedacted(text: string, count: number): string[] {
  const parts: string[] = [];
  let rest = text;
  for (let i = 0; i < count - 1; i++) {
    const at = rest.indexOf(PII_JOIN_BOUNDARY);
    if (at === -1) { parts.push(rest); rest = ''; continue; }
    parts.push(rest.slice(0, at));
    rest = rest.slice(at + PII_JOIN_BOUNDARY.length);
  }
  parts.push(rest);
  return parts;
}

/**
 * Рекурсивно применяет restorePii к каждой строке внутри произвольного
 * JSON-подобного значения (объект/массив/строка) — нужно для ответов модели в
 * структурированном виде (например ExtractionResult из extractDraft или пункты
 * из extractActionItems), где ПД может оказаться в любом строковом поле, а не
 * в одном цельном тексте.
 */
export function restorePiiDeep<T>(value: T, map: PiiMap): T {
  if (typeof value === 'string') return restorePii(value, map) as unknown as T;
  if (Array.isArray(value)) return value.map((v) => restorePiiDeep(v, map)) as unknown as T;
  if (value && typeof value === 'object') {
    const out: Record<string, unknown> = {};
    for (const [k, v] of Object.entries(value as Record<string, unknown>)) out[k] = restorePiiDeep(v, map);
    return out as T;
  }
  return value;
}

/**
 * restorePiiDeep + предупреждение об остаточных токенах — deep-аналог
 * restorePiiAndWarn, тот же формат строки лога (см. formatResidualWarning).
 */
export function restorePiiDeepAndWarn<T>(value: T, map: PiiMap, context: string): T {
  const restored = restorePiiDeep(value, map);
  const residual = findResidualPiiTokens(JSON.stringify(restored));
  if (residual.length) {
    console.warn(formatResidualWarning(context, residual));
  }
  return restored;
}
