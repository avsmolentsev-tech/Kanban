/**
 * Обезличивание персональных данных перед отправкой текста в LLM (152-ФЗ).
 *
 * Формула: наружу — только обезличенный текст, таблица соответствия token → значение
 * остаётся у нас (никогда не логируется, не сохраняется в БД, не индексируется),
 * подстановка исходных значений обратно делается нашим кодом после ответа модели.
 *
 * Покрытые классы данных: телефоны (RU-формат с префиксом, RU-мобильный без
 * префикса, международный `+код`), email, ФИО (двух- и трёхсловные, латиница,
 * сокращённые формы «Фамилия И.О.» / «И. Фамилия»). Осознанно НЕ покрыты: паспорт,
 * ИНН, СНИЛС, дата рождения, почтовый адрес, telegram-хендлы — каждый из них либо
 * легко спутать с обычными числами/словами транскрипта (даты рождения неотличимы
 * от дат встречи без контекста), либо требует отдельной проработки границ и
 * тестов. Замалчивать это не хотим: если понадобится покрыть — это отдельная
 * доработка данного модуля, а не факт, который уже тут "подразумевается".
 */

export type PiiMap = Record<string, string>;

// ── Телефоны ─────────────────────────────────────────────────────────────
// Границы по цифрам (?<!\d) / (?!\d) обязательны: без них "Заказ 89161234567890"
// матчился частично (первые 11 цифр), а хвост "890" утекал в модель как обрывок
// заведомо испорченного числа — то есть визуально выглядело как обезличивание,
// но было им лишь наполовину.
const PHONE_RU = /(?<!\d)(?:\+7|8)[\s(-]*\d{3}[\s)-]*\d{3}[\s-]*\d{2}[\s-]*\d{2}(?!\d)/g;
/** Мобильный без кода страны — так его чаще всего диктуют вслух: "916 123-45-67". */
const PHONE_RU_BARE = /(?<!\d)9\d{2}[\s-]?\d{3}[\s-]?\d{2}[\s-]?\d{2}(?!\d)/g;
/** Любой другой код страны: "+375 29 1234567" и т.п. */
const PHONE_INTL = /(?<!\d)\+\d{1,3}[\s(-]*\d{2,4}[\s)-]*\d{3,4}[\s-]*\d{0,4}[\s-]*\d{0,4}(?!\d)/g;

const EMAIL = /[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}/g;

// ── ФИО ──────────────────────────────────────────────────────────────────
// В JS \b определяется через ASCII \w и не работает на кириллице — граница между
// пробелом и русской буквой для движка не граница (обе стороны "не-словесные"),
// поэтому \b перед/после кириллических слов просто никогда не срабатывает.
// Заменяем его на явные лукэраунды по кириллическому алфавиту (аналогично для
// латиницы — свой лукэраунд по [A-Za-z]).
const CYR = 'А-Яа-яЁё';

/**
 * Два ИЛИ три слова с заглавной подряд — кандидат в ФИО. Жадный (по умолчанию для
 * `?`), поэтому съедает тройную форму «Имя Отчество Фамилия» целиком одним токеном:
 * раньше не жадный вариант останавливался на первых двух словах и оставлял фамилию
 * (самый идентифицирующий компонент) в открытом виде — например
 * «Иван Петрович Сидоров» превращалось в «[УЧАСТНИК_1] Сидоров».
 *
 * Известный компромисс: исключения по границе предложения нет вообще — см. ниже.
 * Различить «Иван Петров» и «Сроки Горят», когда оба стоят в позиции 0 всей строки,
 * средствами одной регулярки без словаря имён нельзя. В транскриптах встреч реплики
 * почти всегда оформлены как «Имя Фамилия: текст» с новой строки — то есть ровно там,
 * где раньше стоявшее исключение срабатывало, и реальные имена спикеров пролетали
 * мимо обезличивания (проверено на синтетическом транскрипте, см. отчёт задачи).
 * Пропуск имени — утечка; лишняя замена в «Сроки Горят потому что…» — испорченный
 * кусок текста, не утечка. Поэтому исключения нет: точность ниже, зато ни одно ФИО
 * не проходит мимо редактирования независимо от позиции в тексте.
 */
const FULLNAME = new RegExp(
  `(?<![${CYR}])([А-ЯЁ][а-яё]{2,})[ \\t]+([А-ЯЁ][а-яё]{2,})(?:[ \\t]+([А-ЯЁ][а-яё]{2,}))?(?![${CYR}])`,
  'g'
);
/** Латинские имена: «John Smith», «Anna Lee» — участники из международных встреч. */
const LATIN_NAME = /(?<![A-Za-z])([A-Z][a-z]{2,})[ \t]+([A-Z][a-z]{2,})(?![A-Za-z])/g;
/** «Ольга К.» / «Петров И.И.» — имя или фамилия с одним-двумя инициалами после. */
const INITIALS_AFTER = new RegExp(`(?<![${CYR}])([А-ЯЁ][а-яё]{2,})[ \\t]+((?:[А-ЯЁ]\\.){1,2})(?![${CYR}])`, 'g');
/** «А. Смирнов» / «И.О. Петров» — один-два инициала перед фамилией. */
const INITIALS_BEFORE = new RegExp(`(?<![${CYR}])((?:[А-ЯЁ]\\.){1,2})[ \\t]?([А-ЯЁ][а-яё]{2,})(?![${CYR}])`, 'g');
/** Одиночное слово-кандидат — сверяется со словарём компонентов, найденных выше. */
const SINGLE_CYR_WORD = new RegExp(`(?<![${CYR}])([А-ЯЁ][а-яё]{2,})(?![${CYR}])`, 'g');
const SINGLE_LATIN_WORD = /(?<![A-Za-z])([A-Z][a-z]{2,})(?![A-Za-z])/g;
/** Инициал вида "И." или "И.О." — не самостоятельное слово, в словарь компонентов не идёт. */
const IS_INITIALS_GROUP = /^[А-ЯЁ]\.([А-ЯЁ]\.)?$/;

/**
 * Заменяет персональные данные на стабильные токены.
 * В модель уходит только `text`; `map` остаётся на нашей стороне и в логи/промпты
 * не попадает никогда — вызывающий код обязан держать её только в переменной.
 *
 * Многословные и сокращённые формы ФИО обрабатываются первым проходом. Второй
 * проход ищет одиночные слова, которые уже встретились как компонент найденного
 * имени (например «Иван» после «Иван Петров:» в реплике дальше по тексту), и
 * помечает их тем же токеном участника — без словаря имён, только по совпадению
 * с уже найденным компонентом. У полностью изолированного упоминания («Иван,
 * ты успеешь?» без единого другого упоминания имени во всём тексте) нет ничего,
 * с чем сверяться — это осознанная граница метода, а не словарь имён.
 */
export function redactPii(text: string): { text: string; map: PiiMap } {
  const map: PiiMap = {};
  const seen = new Map<string, string>();
  const counters: Record<string, number> = { ТЕЛЕФОН: 0, EMAIL: 0, УЧАСТНИК: 0 };
  const nameComponents = new Map<string, string>();

  const registerComponents = (groups: Array<string | undefined>, token: string): void => {
    for (const g of groups) {
      if (!g || IS_INITIALS_GROUP.test(g)) continue;
      if (!nameComponents.has(g)) nameComponents.set(g, token);
    }
  };

  const replace = (input: string, re: RegExp, kind: string, onGroups?: (groups: Array<string | undefined>, token: string) => void): string =>
    input.replace(re, (match: string, ...rest: unknown[]) => {
      const groups = rest.filter((g): g is string => typeof g === 'string');
      const existing = seen.get(match);
      if (existing) return existing;
      counters[kind] = (counters[kind] ?? 0) + 1;
      const token = `[${kind}_${counters[kind]}]`;
      seen.set(match, token);
      map[token] = match;
      onGroups?.(groups, token);
      return token;
    });

  let out = text;
  out = replace(out, EMAIL, 'EMAIL');
  out = replace(out, PHONE_RU, 'ТЕЛЕФОН');
  out = replace(out, PHONE_RU_BARE, 'ТЕЛЕФОН');
  out = replace(out, PHONE_INTL, 'ТЕЛЕФОН');
  out = replace(out, FULLNAME, 'УЧАСТНИК', registerComponents);
  out = replace(out, LATIN_NAME, 'УЧАСТНИК', registerComponents);
  out = replace(out, INITIALS_AFTER, 'УЧАСТНИК', registerComponents);
  out = replace(out, INITIALS_BEFORE, 'УЧАСТНИК', registerComponents);

  // Второй проход: одиночные слова, уже встреченные как компонент найденного имени.
  out = out.replace(SINGLE_CYR_WORD, (m) => nameComponents.get(m) ?? m);
  out = out.replace(SINGLE_LATIN_WORD, (m) => nameComponents.get(m) ?? m);

  return { text: out, map };
}

const TOKEN_KINDS = ['ТЕЛЕФОН', 'EMAIL', 'УЧАСТНИК'] as const;
/**
 * Терпима к регистру и разделителю: модель, пишущая связное резюме, может отдать
 * «Участник 1», «[Участник_1]» или «[УЧАСТНИК 1]» вместо точного «[УЧАСТНИК_1]».
 * Без этой терпимости restorePii менял бы только точные совпадения, и искажённый
 * токен молча оставался бы в тексте — а оттуда в БД и в поисковый индекс.
 */
const TOLERANT_TOKEN_RE = new RegExp(`\\[\\s*(${TOKEN_KINDS.join('|')})[\\s_]*(\\d+)\\s*\\]`, 'gi');

/**
 * Подстановка реальных значений обратно — уже у нас, без участия модели.
 *
 * Известный остаточный риск (принят осознанно, не устранён): если бы в САМОМ
 * транскрипте до обезличивания буквально встретилась строка вида «[EMAIL_1]»
 * (что практически невозможно для расшифровки речи), restorePii подставила бы
 * туда чужой адрес из карты. Это неизбежное следствие любой плейсхолдер-схемы;
 * при формате токена, не встречающемся в естественной речи, риск пренебрежимо мал.
 */
export function restorePii(text: string, map: PiiMap): string {
  return text.replace(TOLERANT_TOKEN_RE, (whole, kindRaw: string, num: string) => {
    const kind = TOKEN_KINDS.find((k) => k.toLowerCase() === kindRaw.toLowerCase());
    if (!kind) return whole;
    const canonical = `[${kind}_${num}]`;
    return Object.prototype.hasOwnProperty.call(map, canonical) ? map[canonical]! : whole;
  });
}

/**
 * Сканирует текст ПОСЛЕ restorePii на остаточные токены — те, что модель исказила
 * настолько, что даже терпимый restorePii не смог их опознать (несуществующий
 * номер участника, мусор внутри скобок и т.п.). Возвращает сами строки токенов —
 * НИКОГДА значения из таблицы соответствия, — вызывающий код обязан логировать
 * только их: `console.warn('...', findResidualPiiTokens(summary))`.
 */
export function findResidualPiiTokens(text: string): string[] {
  const re = new RegExp(`\\[\\s*(?:${TOKEN_KINDS.join('|')})[\\s_]*\\d*\\s*\\]`, 'gi');
  return [...new Set(text.match(re) ?? [])];
}
