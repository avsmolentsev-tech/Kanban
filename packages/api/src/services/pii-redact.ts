/**
 * Обезличивание персональных данных перед отправкой текста в LLM (152-ФЗ).
 *
 * Формула: наружу — только обезличенный текст, таблица соответствия token → значение
 * остаётся у нас (никогда не логируется, не сохраняется в БД, не индексируется),
 * подстановка исходных значений обратно делается нашим кодом после ответа модели.
 */

export type PiiMap = Record<string, string>;

const PHONE = /(?:\+7|8)[\s(-]*\d{3}[\s)-]*\d{3}[\s-]*\d{2}[\s-]*\d{2}/g;
const EMAIL = /[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}/g;

// В JS \b определяется через ASCII \w и не работает на кириллице — граница между
// пробелом и русской буквой для движка не граница (обе стороны "не-словесные"),
// поэтому \b перед/после кириллических слов просто никогда не срабатывает.
// Заменяем его на явные лукэраунды по кириллическому алфавиту.
const CYR = 'А-Яа-яЁё';
/**
 * Два слова с заглавной буквы подряд — кандидат в ФИО.
 *
 * Известный компромисс: изначально здесь стоял лукбехайнд, отсекающий капитализацию
 * в начале предложения (после «.», «!», «?» + пробел/перенос строки). На синтетической
 * проверке (см. отчёт задачи) он оказался опасным: в транскриптах встреч реплики почти
 * всегда оформлены как «Имя Фамилия: текст» с новой строки — то есть ровно там, где
 * это исключение срабатывает, и реальные имена спикеров пролетали мимо обезличивания.
 * Пропуск имени — утечка; лишняя замена в «Сроки Горят потому что…» — просто испорченный
 * кусок текста. Поэтому исключение по границе предложения убрано: точность ниже,
 * зато ни одно ФИО не проходит мимо редактирования независимо от позиции в тексте.
 */
const FULLNAME = new RegExp(`(?<![${CYR}])([А-ЯЁ][а-яё]{2,})[ \\t]+([А-ЯЁ][а-яё]{2,})(?![${CYR}])`, 'g');

/**
 * Заменяет персональные данные на стабильные токены.
 * В модель уходит только `text`; `map` остаётся на нашей стороне и в логи/промпты
 * не попадает никогда — вызывающий код обязан держать её только в переменной.
 */
export function redactPii(text: string): { text: string; map: PiiMap } {
  const map: PiiMap = {};
  const seen = new Map<string, string>();
  const counters: Record<string, number> = { ТЕЛЕФОН: 0, EMAIL: 0, УЧАСТНИК: 0 };

  const replace = (input: string, re: RegExp, kind: string): string =>
    input.replace(re, (match) => {
      const existing = seen.get(match);
      if (existing) return existing;
      counters[kind] = (counters[kind] ?? 0) + 1;
      const token = `[${kind}_${counters[kind]}]`;
      seen.set(match, token);
      map[token] = match;
      return token;
    });

  let out = text;
  out = replace(out, EMAIL, 'EMAIL');
  out = replace(out, PHONE, 'ТЕЛЕФОН');
  out = replace(out, FULLNAME, 'УЧАСТНИК');
  return { text: out, map };
}

/** Подстановка реальных значений обратно — уже у нас, без участия модели. */
export function restorePii(text: string, map: PiiMap): string {
  let out = text;
  for (const [token, original] of Object.entries(map)) {
    out = out.split(token).join(original);
  }
  return out;
}
